export function computeEquipmentStats(equipped: EquippedGear): EquipmentStats {
  let warmth = 0;
  let heatResist = 0;
  let windRainResist = 0;
  let staminaSave = 0;
  let blendChance = 0;
  let weightKg = 0;

  for (const slot of ["hat", "torso", "legs", "feet", "accessory"] as const) {
    const id = equipped[slot];
    if (!id) continue;
    const def = GARMENT_BY_ID[id];
    if (!def) continue;
    warmth += def.warmth;
    heatResist += def.heatResist;
    windRainResist += def.windRainResist;
    staminaSave += def.staminaSave;
    blendChance += def.blendChance ?? GARMENT_BLEND_CHANCE[def.id] ?? 0;
    weightKg += def.weightKg;
  }

  return {
    warmth,
    heatResist: Math.min(1.0, heatResist),
    windRainResist: Math.min(0.95, windRainResist),
    staminaSave: Math.min(0.45, staminaSave),
    blendChance: Number(Math.min(MAX_BLEND_CHANCE, blendChance).toFixed(2)),
    weightKg: Number(weightKg.toFixed(2)),
  };
}

