export interface ConsumableDef {
  id: string;
  inventoryItemId: string;
  name: string;
  shopCategory: "food" | "pharmacy";
  mapOrigin?: MapId;
  priceGold: number;
  weightKg: number;
  gridW: number;
  gridH: number;
  maxUses: number;
  hungerRestore: number;
  staminaRestore: number;
  hpRestore: number;
  /** Negative cools body temp in hot sun; positive warms up in cold/rain */
  tempDeltaC: number;
  /** Real-time consumption/eating progress duration in milliseconds */
  useDurationMs: number;
  /** Optional temporary stamina boost percentage (20, 50, 80) */
  staminaBoostPct?: number;
  /** Duration of temporary stamina boost in milliseconds (1/5/10 minutes) */
  staminaBoostDurationMs?: number;
  /** Restores HP, hunger, stamina to full cap and stabilizes body temperature */
  isFullRestore?: boolean;
  emoji: string;
  description: string;
  iconSrc: string;
}

export function getConsumableSingleUsePrice(def: ConsumableDef): number {
  return Math.max(5, Math.ceil(def.priceGold / Math.max(1, def.maxUses)));
}

function makeEmojiIconDataUrl(emoji: string, bgHex: string, borderHex: string): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 48 48"><rect x="2" y="2" width="44" height="44" rx="10" fill="${bgHex}" stroke="${borderHex}" stroke-width="2.5"/><text x="24" y="31" text-anchor="middle" font-size="25">${emoji}</text></svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

